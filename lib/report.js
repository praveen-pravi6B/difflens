import fs from 'node:fs';
import path from 'node:path';
import { ARTIFACT_DIR, escapeHtml, formatDuration } from './util.js';

export function buildReportHtml(result) {
  const dir = path.join(ARTIFACT_DIR, result.id);
  const image = (name) => {
    const file = path.join(dir, name);
    if (!fs.existsSync(file)) return null;
    return `data:image/png;base64,${fs.readFileSync(file).toString('base64')}`;
  };
  const localShot = image('local.png');
  const stagingShot = image('staging.png');
  const diffShot = image('diff.png');

  const { content, markup, visual, summary } = result;
  const verdictClass = summary.identical ? 'ok' : 'changed';
  const verdictText = summary.identical ? 'No differences detected' : 'Differences found';
  const visualPercent = visual.available ? (visual.ratio * 100).toFixed(2) : null;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>DiffLens report — ${escapeHtml(result.urls.local)} vs ${escapeHtml(result.urls.staging)}</title>
<style>${REPORT_CSS}</style>
</head>
<body>
<header class="report-head">
  <div>
    <div class="brand">DiffLens <span>report</span></div>
    <h1>${escapeHtml(result.local.title || result.urls.local)} <span class="vs">vs</span> ${escapeHtml(result.staging.title || result.urls.staging)}</h1>
  </div>
  <div class="meta">
    <div>${escapeHtml(new Date(result.createdAt).toLocaleString())}</div>
    <div>${escapeHtml(result.engine.name)} ${escapeHtml(result.engine.version || '')} · ${result.engine.viewport.width}×${result.engine.viewport.height}</div>
    <div>${escapeHtml(result.engine.screenshotMode)} capture</div>
  </div>
</header>

<section class="targets">
  <div class="target local">
    <span class="dot"></span>
    <div><div class="label">Local (candidate)</div><div class="url">${escapeHtml(result.urls.local)}</div></div>
  </div>
  <div class="target staging">
    <span class="dot"></span>
    <div><div class="label">Staging (baseline)</div><div class="url">${escapeHtml(result.urls.staging)}</div></div>
  </div>
</section>

<section class="verdict ${verdictClass}">
  <div>
    <div class="verdict-title">${verdictText}</div>
    <div class="verdict-sub">${summary.totalChanges} content/markup changes · ${visual.available ? `${visualPercent}% of pixels differ` : 'pixel diff unavailable'}</div>
  </div>
  <div class="score">${summary.identical ? '100' : Math.max(0, Math.round(summary.similarity))}<span>/100 content similarity</span></div>
</section>

<section class="stats">
  <div class="stat"><b>${content.stats.added}</b><span>new lines</span></div>
  <div class="stat"><b>${content.stats.removed}</b><span>removed lines</span></div>
  <div class="stat"><b>${content.stats.changed}</b><span>changed lines</span></div>
  <div class="stat"><b>${markup.stats.added}</b><span>new elements</span></div>
  <div class="stat"><b>${markup.stats.removed}</b><span>removed elements</span></div>
  <div class="stat"><b>${markup.stats.changed}</b><span>changed elements</span></div>
  <div class="stat"><b>${visual.mismatchPixels ? visual.mismatchPixels.toLocaleString() : '—'}</b><span>diff pixels</span></div>
</section>

${result.warnings.length ? `<section class="warnings"><h2>Warnings</h2><ul>${result.warnings.map((w) => `<li>${escapeHtml(w)}</li>`).join('')}</ul></section>` : ''}

<section class="block">
  <h2>Visual diff</h2>
  ${diffShot ? `<img class="diff-image" src="${diffShot}" alt="Pixel differences highlighted in pink">` : `<p class="muted">Pixel diff unavailable.</p>`}
  ${visual.bbox ? `<p class="muted">First changed region: x ${visual.bbox.x}, y ${visual.bbox.y} — ${visual.bbox.width}×${visual.bbox.height}px.</p>` : ''}
  <div class="shots">
    ${localShot ? `<figure><figcaption>Local</figcaption><img src="${localShot}" alt="Local screenshot"></figure>` : ''}
    ${stagingShot ? `<figure><figcaption>Staging</figcaption><img src="${stagingShot}" alt="Staging screenshot"></figure>` : ''}
  </div>
</section>

<section class="block">
  <h2>Content diff <span class="muted">(${content.stats.similarity}% similar)</span></h2>
  ${renderContent(content)}
</section>

<section class="block">
  <h2>Markup diff</h2>
  ${renderMarkup(markup)}
</section>

<section class="block">
  <h2>Diagnostics</h2>
  <div class="diag-grid">
    ${renderDiagnostics(result.local, 'Local')}
    ${renderDiagnostics(result.staging, 'Staging')}
  </div>
</section>

<footer class="foot">
  Generated by DiffLens · ${escapeHtml(result.id)} · ${formatDuration(result.timings.totalMs)}
</footer>
</body>
</html>`;
}

function renderContent(content) {
  if (!content.hunks.length) return `<p class="muted">The visible text is identical.</p>`;
  return content.hunks
    .map(
      (hunk) => `<div class="hunk">
  <div class="hunk-head">@@ staging ${hunk.oldStart} · local ${hunk.newStart} @@ <span>${hunk.changes} change${hunk.changes === 1 ? '' : 's'}</span></div>
  <table class="diff-table">
    ${hunk.rows
      .map((row) => {
        if (row.kind === 'mod') {
          return `<tr class="mod"><td class="ln">${row.oldLine}</td><td class="ln">${row.newLine}</td><td class="marker">~</td><td class="code"><span class="del">${segments(row.oldSegments, 'del')}</span><br><span class="add">${segments(row.newSegments, 'add')}</span></td></tr>`;
        }
        if (row.kind === 'add') {
          return `<tr class="add"><td class="ln"></td><td class="ln">${row.newLine}</td><td class="marker">+</td><td class="code"><span class="add">${escapeHtml(row.newText)}</span></td></tr>`;
        }
        if (row.kind === 'del') {
          return `<tr class="del"><td class="ln">${row.oldLine}</td><td class="ln"></td><td class="marker">−</td><td class="code"><span class="del">${escapeHtml(row.oldText)}</span></td></tr>`;
        }
        return `<tr class="same"><td class="ln">${row.oldLine}</td><td class="ln">${row.newLine}</td><td class="marker"></td><td class="code">${escapeHtml(row.oldText) || '&nbsp;'}</td></tr>`;
      })
      .join('')}
  </table>
</div>`,
    )
    .join('');
}

function segments(list, mode) {
  if (!list) return '';
  return list
    .map((segment) => {
      if (segment.k === 'same') return escapeHtml(segment.t);
      return `<span class="seg ${segment.k}">${escapeHtml(segment.t)}</span>`;
    })
    .join('');
}

function renderMarkup(markup) {
  const blocks = [];
  if (markup.added.length) {
    blocks.push(`<h3 class="added">New in local (${markup.stats.added})</h3><ul class="el-list">${markup.added
      .map((item) => `<li><code>${escapeHtml(item.path)}</code> <span class="tag">${escapeHtml(item.tag)}</span> ${escapeHtml(item.text)}</li>`)
      .join('')}</ul>`);
  }
  if (markup.removed.length) {
    blocks.push(`<h3 class="removed">Missing from local (${markup.stats.removed})</h3><ul class="el-list">${markup.removed
      .map((item) => `<li><code>${escapeHtml(item.path)}</code> <span class="tag">${escapeHtml(item.tag)}</span> ${escapeHtml(item.text)}</li>`)
      .join('')}</ul>`);
  }
  if (markup.changed.length) {
    blocks.push(`<h3 class="changed">Changed elements (${markup.stats.changed})</h3><ul class="el-list">${markup.changed
      .map((item) => {
        const text = item.text
          ? `<div class="el-text"><span class="del">${escapeHtml(item.text.from)}</span> → <span class="add">${escapeHtml(item.text.to)}</span></div>`
          : '';
        const attrs = item.attrs
          .map((attr) => `<div class="attr"><b>${escapeHtml(attr.name)}</b>: <span class="del">${escapeHtml(attr.from || '∅')}</span> → <span class="add">${escapeHtml(attr.to || '∅')}</span></div>`)
          .join('');
        return `<li><code>${escapeHtml(item.path)}</code> <span class="tag">${escapeHtml(item.tag)}</span>${text}${attrs}</li>`;
      })
      .join('')}</ul>`);
  }
  return blocks.length ? blocks.join('') : `<p class="muted">No markup changes were detected.</p>`;
}

function renderDiagnostics(side, label) {
  const diag = side.diagnostics || {};
  const errors = [
    ...(diag.pageErrors || []).map((e) => `Page error: ${e}`),
    ...(diag.consoleErrors || []).map((e) => `Console: ${e}`),
    ...(diag.failedRequests || []).map((e) => `Failed: ${e.method} ${e.url} (${e.error})`),
    ...(diag.httpErrors || []).map((e) => `HTTP ${e.status}: ${e.url}`),
  ];
  return `<div class="diag">
  <div class="diag-head"><b>${escapeHtml(label)}</b><span class="pill">${side.httpStatus ? `HTTP ${side.httpStatus}` : 'no status'}</span></div>
  <div class="diag-url">${escapeHtml(side.finalUrl)}</div>
  <div class="kv"><span>Title</span><b>${escapeHtml(side.title || '—')}</b></div>
  <div class="kv"><span>Viewport</span><b>${side.viewport?.width || '?'}×${side.viewport?.height || '?'}</b></div>
  <div class="kv"><span>Page height</span><b>${side.documentHeight || '?'} px</b></div>
  <div class="kv"><span>Visible text</span><b>${(side.textChars || 0).toLocaleString()} chars</b></div>
  <div class="kv"><span>Elements</span><b>${side.elements || 0}</b></div>
  <div class="kv"><span>Links / buttons / images</span><b>${side.counts?.links || 0} / ${side.counts?.buttons || 0} / ${side.counts?.images || 0}</b></div>
  <div class="kv"><span>Capture time</span><b>${formatDuration(side.timings?.totalMs)}</b></div>
  ${errors.length ? `<div class="errors"><b>${errors.length} issue${errors.length === 1 ? '' : 's'}</b><ul>${errors.map((e) => `<li>${escapeHtml(e)}</li>`).join('')}</ul></div>` : `<p class="ok-line">No console errors, page errors or failed requests.</p>`}
</div>`;
}

